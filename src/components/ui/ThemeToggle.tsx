import { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { getInitialTheme, THEME_STORAGE_KEY, type Theme } from '../../utils/theme';

export default function ThemeToggle() {
  const [searchParams] = useSearchParams();
  const [theme, setTheme] = useState<Theme>(() => getInitialTheme(searchParams.get('theme')));

  useEffect(() => {
    document.documentElement.setAttribute('data-theme', theme);
    window.localStorage.setItem(THEME_STORAGE_KEY, theme);
  }, [theme]);

  const toggleTheme = () => setTheme((prev) => (prev === 'dark' ? 'light' : 'dark'));

  return (
    <button
      onClick={toggleTheme}
      className="fixed bottom-5 right-5 bg-card border border-card-border rounded-full w-10 h-10 flex items-center justify-center cursor-pointer text-text-sub hover:text-text-main transition-colors z-50"
      title="Toggle theme"
      aria-label="Toggle theme"
    >
      {theme === 'dark' ? (
        <svg width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24">
          <circle cx="12" cy="12" r="5"></circle>
          <path d="M12 1v2M12 21v2M4.22 4.22l1.42 1.42M18.36 18.36l1.42 1.42M1 12h2M21 12h2M4.22 19.78l1.42-1.42M18.36 5.64l1.42-1.42"></path>
        </svg>
      ) : (
        <svg width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24">
          <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z"></path>
        </svg>
      )}
    </button>
  );
}
